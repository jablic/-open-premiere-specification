LOCAL_TOOLS = ROOT / 'tools'
if str(LOCAL_TOOLS) not in sys.path:
    sys.path.insert(0, str(LOCAL_TOOLS))
from ppaikb_builder.cli import compile_repo, build_repo, validate_repo, rag_repo
cmd = sys.argv[1] if len(sys.argv) > 1 else 'build'
if cmd == 'compile': compile_repo(ROOT)
