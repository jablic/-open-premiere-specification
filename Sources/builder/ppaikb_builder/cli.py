def yaml_dump(data: dict[str, Any]) -> str:
    if yaml is not None:
        return yaml.safe_dump(data, allow_unicode=True, sort_keys=False)
    # fallback not expected
    return json.dumps(data, ensure_ascii=False, indent=2)


def render_list_section(lines: list[str], title: str, items: Any) -> None:
    if not items:
        return
    lines += [f'## {title}', '']
    if isinstance(items, list):
        for item in items:
            lines.append(f'- {item}')
    else:
        lines.append(str(items))
    lines.append('')


def render_spec(doc: SpecDoc) -> str:
    d = doc.data
    lines: list[str] = []
    lines.append(f"# {doc.title} `{doc.doc_id}`")
    lines.append('')
    lines.append(f"**Kind:** `{doc.kind}`  ")
    lines.append(f"**Status:** `{d.get('status', 'draft')}`  ")
    lines.append(f"**Confidence:** `{d.get('confidence', 'unknown')}`  ")
    lines.append(f"**Source:** `{doc.source.relative_to(doc.source.parents[1]).as_posix() if len(doc.source.parents)>1 else doc.source.name}`")
    lines.append('')
    if d.get('summary'):
        lines += ['## Summary', '', str(d['summary']), '']
    for key, title in [('owns','Owns'),('references','References'),('contains','Contains'),('constraints','Constraints'),('ai_rules','AI Rules'),('anti_patterns','Anti-patterns'),('symptoms','Symptoms')]:
        render_list_section(lines, title, d.get(key))
    if d.get('steps'):
        lines += ['## Procedure', '']
        for i, item in enumerate(d['steps'],1): lines.append(f'{i}. {item}')
        lines.append('')
    for key,title in [('given','Given'),('when','When'),('then','Then'),('cause','Cause'),('workaround','Workaround')]:
        if d.get(key):
            lines += [f'## {title}', '', str(d[key]), '']
    if doc.kind == 'object':
        lines += ['## Object Graph', '', '```mermaid', 'graph TD']
        root = safe_node(doc.doc_id)
        lines.append(f'  {root}["{doc.title}"]')
        for item in d.get('owns',[]) or []:
            lines.append(f'  {root} -->|owns| {safe_node(str(item))}["{item}"]')
        for item in d.get('references',[]) or []:
            lines.append(f'  {root} -.->|references| {safe_node(str(item))}["{item}"]')
        lines += ['```','']
    if d.get('related'):
        lines += ['## Related', '']
        for item in d['related']: lines.append(f'- `{item}`')
        lines.append('')
    lines += ['## Validation Checklist','', '- [ ] Identity and scope are explicit.', '- [ ] Ownership and references are explicit.', '- [ ] Unsafe assumptions are not presented as confirmed.', '- [ ] AI rules are actionable.', '- [ ] Anti-patterns are documented.', '']
    return '\n'.join(lines)


def safe_node(s: str) -> str:
    return re.sub(r'[^A-Za-z0-9_]', '_', s)


def load_specs(target: Path) -> list[SpecDoc]:
    if yaml is None:
        raise RuntimeError('PyYAML is required. Install with: pip3 install PyYAML')
    specs = []
    for path in sorted((target / 'spec_src').rglob('*.yaml')):
        data = yaml.safe_load(path.read_text(encoding='utf-8')) or {}
        specs.append(SpecDoc(path, data))
    return specs


def compile_repo(target: Path) -> None:
    specs = load_specs(target)
    for spec in specs:
        write(target / 'docs' / spec.output, render_spec(spec))
    graph = build_graph_data(specs)
    twin = build_digital_twin(specs)
    rulepack = build_rulepack(specs)
    tests = build_test_manifest(specs)
    coverage = build_coverage(specs)
    write(target / 'knowledge_graph.json', json.dumps(graph, ensure_ascii=False, indent=2))
    write(target / 'digital_twin.json', json.dumps(twin, ensure_ascii=False, indent=2))
    write(target / 'ai_rulepack.json', json.dumps(rulepack, ensure_ascii=False, indent=2))
    write(target / 'test_manifest.json', json.dumps(tests, ensure_ascii=False, indent=2))
    write(target / 'coverage_report.json', json.dumps(coverage, ensure_ascii=False, indent=2))
    write(target / 'docs/12_GRAPH/knowledge-graph.md', render_graph_markdown(graph))
    write(target / 'docs/13_DIGITAL_TWIN/digital-twin.md', render_digital_twin_markdown(twin))
    write(target / 'docs/14_AI_RULEPACK/ai-rulepack.md', render_rulepack_markdown(rulepack))
    write(target / 'docs/15_TEST_MANIFEST/test-manifest.md', render_test_manifest_markdown(tests))
    write(target / 'docs/16_REPORTS/coverage-report.md', render_coverage_markdown(coverage))
    print(f'Compiled {len(specs)} DSL specs.')


def build_graph_data(specs: list[SpecDoc]) -> dict[str, Any]:
    nodes, edges = [], []
    for s in specs:
        nodes.append({'id':s.doc_id,'title':s.title,'kind':s.kind,'output':s.output,'confidence':s.data.get('confidence','unknown')})
        for key, etype in [('related','related'),('owns','owns'),('references','references')]:
            for target in s.data.get(key,[]) or []:
                edges.append({'source':s.doc_id,'target':str(target),'type':etype})
    return {'version': VERSION, 'nodes':nodes, 'edges':edges}


def payload(s: SpecDoc) -> dict[str, Any]:
    keys = ['summary','owns','references','contains','constraints','ai_rules','anti_patterns','related','steps','symptoms','cause','workaround','given','when','then']
    p = {'id':s.doc_id,'title':s.title,'kind':s.kind,'confidence':s.data.get('confidence','unknown'),'status':s.data.get('status','draft'),'output':s.output}
    for k in keys:
        if k in s.data: p[k] = s.data.get(k)
    return p


def build_digital_twin(specs: list[SpecDoc]) -> dict[str, Any]:
    groups: dict[str, dict[str, Any]] = {k:{} for k in ['object','serialization','api','rule','recipe','pattern','bug','test','experiment','benchmark','evaluation','dataset']}
    for s in specs:
        groups.setdefault(s.kind,{})[s.doc_id] = payload(s)
    return {'version':VERSION, **{k+'s':v for k,v in groups.items()}}


def build_rulepack(specs: list[SpecDoc]) -> dict[str, Any]:
    rules = [payload(s) for s in specs if s.kind == 'rule']
    extracted = []
    for s in specs:
        for r in s.data.get('ai_rules',[]) or []:
            extracted.append({'source':s.doc_id,'rule':str(r)})
    return {'version':VERSION,'declared_rules':rules,'extracted_ai_rules':extracted}


def build_test_manifest(specs: list[SpecDoc]) -> dict[str, Any]:
    return {'version':VERSION,'tests':[payload(s) for s in specs if s.kind in ('test','benchmark','evaluation')]}


def build_coverage(specs: list[SpecDoc]) -> dict[str, Any]:
    by_kind: dict[str,int] = {}
    confidence: dict[str,int] = {}
    missing_related = []
    for s in specs:
        by_kind[s.kind] = by_kind.get(s.kind,0)+1
        c = str(s.data.get('confidence','unknown'))
        confidence[c] = confidence.get(c,0)+1
        if not s.data.get('related'):
            missing_related.append(s.doc_id)
    return {'version':VERSION,'total_specs':len(specs),'by_kind':by_kind,'by_confidence':confidence,'missing_related':missing_related}


