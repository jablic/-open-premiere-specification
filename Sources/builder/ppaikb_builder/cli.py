@dataclass
class SpecDoc:
    source: Path
    data: dict[str, Any]

    @property
    def doc_id(self) -> str:
        return str(self.data.get('id', self.source.stem))

    @property
    def title(self) -> str:
        return str(self.data.get('title', self.doc_id))

    @property
    def kind(self) -> str:
        return str(self.data.get('kind', 'spec'))

    @property
    def output(self) -> str:
        if self.data.get('output'):
            return str(self.data['output'])
        folder = KIND_FOLDERS.get(self.kind, '99_GENERATED')
        return f'{folder}/{self.doc_id.lower()}-{slugify(self.title)}.md'


def slugify(text: str) -> str:
    s = re.sub(r'[^A-Za-z0-9]+', '-', text.strip()).strip('-').lower()
    return s or 'document'


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding='utf-8')


def read_first_heading(path: Path) -> str:
    for line in path.read_text(encoding='utf-8').splitlines():
        if line.startswith('#'):
            return line.lstrip('# ').replace('`', '').strip()
    return path.stem.replace('-', ' ').replace('_', ' ').title()


