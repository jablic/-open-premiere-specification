def build_repo(target: Path) -> None:
    docs = target / 'docs'
    nav_lines = ['site_name: Premiere Pro Open AI Specification','theme:','  name: material','  features:','    - navigation.sections','    - navigation.expand','    - content.code.copy','markdown_extensions:','  - admonition','  - pymdownx.superfences','  - pymdownx.details','nav:','  - Home: index.md']
    for md in sorted(docs.rglob('*.md')):
        rel = md.relative_to(docs).as_posix()
        if rel == 'index.md': continue
        title = read_first_heading(md).replace(':',' -')
        nav_lines.append(f'  - {title}: {rel}')
    write(target / 'mkdocs.yml', '\n'.join(nav_lines)+'\n')
    write(target / 'SUMMARY.md', generate_summary(docs))
    print('Built mkdocs.yml and SUMMARY.md')


def generate_summary(docs: Path) -> str:
    lines = ['# Summary','']
    for md in sorted(docs.rglob('*.md')):
        rel = md.relative_to(docs).as_posix()
        lines.append(f'- [{read_first_heading(md)}](docs/{rel})')
    return '\n'.join(lines)+'\n'


def validate_repo(target: Path) -> None:
    errors=[]
    docs=target/'docs'
    mk=target/'mkdocs.yml'
    if not mk.exists(): errors.append('mkdocs.yml missing')
    else:
        for line in mk.read_text(encoding='utf-8').splitlines():
            m=re.search(r':\s+(.+\.md)$', line.strip())
            if m and not (docs/m.group(1).strip()).exists(): errors.append(f'nav target missing: {m.group(1).strip()}')
    specs=load_specs(target)
    seen={}
    for s in specs:
        if not ID_RE.match(s.doc_id): errors.append(f'invalid id: {s.doc_id}')
        if s.doc_id in seen: errors.append(f'duplicate id: {s.doc_id}')
        seen[s.doc_id]=s.source.as_posix()
        if not s.data.get('summary'): errors.append(f'missing summary: {s.doc_id}')
    for fn in ['knowledge_graph.json','digital_twin.json','ai_rulepack.json','test_manifest.json','coverage_report.json']:
        if not (target/fn).exists(): errors.append(f'missing generated artifact: {fn}')
    report={'errors':errors,'spec_count':len(specs),'ids':sorted(seen.keys())}
    write(target/'validation_report.json', json.dumps(report, ensure_ascii=False, indent=2))
    if errors: raise SystemExit('Validation failed:\n'+'\n'.join(errors))
    print('OK: validation passed.')


def rag_repo(target: Path) -> None:
    chunks=[]
    for md in sorted((target/'docs').rglob('*.md')):
        text=md.read_text(encoding='utf-8')
        parts=re.split(r'\n(?=## )', text)
        for idx,part in enumerate(parts):
            part=part.strip()
            if len(part)<20: continue
            chunks.append({'source':md.relative_to(target/'docs').as_posix(),'chunk_index':idx,'text':part})
    write(target/'rag_chunks.jsonl', '\n'.join(json.dumps(c,ensure_ascii=False) for c in chunks)+'\n')
    print(f'Generated {len(chunks)} RAG chunks.')


def create_repo(target: Path, force: bool=False) -> None:
    if target.exists() and force: shutil.rmtree(target)
    target.mkdir(parents=True, exist_ok=True)
    for rel,text in base_markdown_docs().items(): write(target/'docs'/rel, text)
    for rel,text in initial_yaml_specs().items(): write(target/'spec_src'/rel, text)
    write(target/'requirements.txt','mkdocs>=1.5.0\nmkdocs-material>=9.5.0\nPyYAML>=6.0.1\n')
    write(target/'.gitignore','site/\n__pycache__/\n.DS_Store\n.build/\n')
    write(target/'tools/ppaikb.py', tool_script())
    pkg_dst=target/'tools/ppaikb_builder'
    if pkg_dst.exists(): shutil.rmtree(pkg_dst)
    shutil.copytree(Path(__file__).resolve().parent, pkg_dst, ignore=shutil.ignore_patterns('__pycache__'))
    compile_repo(target); build_repo(target); validate_repo(target); rag_repo(target)
    print(f'Initialized repository: {target}')


